import { describe, expect, test } from 'vitest';
import { parseStory, parseTasks, taskIndex, taskLayoutIssues, withIndex } from '../../src/spec/index.js';

const story = parseStory(`---
schema_version: 1
tracker: none
type: story
id: MDO-9
projects: [shop]
status: approved
---

# Checkout

## Acceptance criteria

### AC-1 — Pay by card
critical: true

- **GIVEN** a cart **WHEN** paying **THEN** paid

### AC-2 — Refund
critical: false

- **GIVEN** a payment **WHEN** refunding **THEN** refunded
`).story!;

const task = (id: string, title: string, yaml: string, body = '- **What:** does it.\n- **Done when:**\n  - S-1.1 holds.') =>
  `### [ ] ${id} — ${title}\n\n${body}\n\n\`\`\`yaml\n${yaml}\n\`\`\`\n`;
const T1 = `project: shop
kind: feat
tier: standard
files: [src/pay.ts]
ac: [AC-1, AC-1/C1]
scenarios: [S-1.1, S-1.1/C1]
test_levels: { S-1.1: e2e, S-1.1/C1: unit }
evidence: tdd
depends_on: []
parallel_safe: true
verify: npm test -- pay`;
const T2 = `project: shop
kind: feat
tier: fast
files: [src/refund.ts]
ac: [AC-2]
scenarios: [S-2.1]
test_levels: { S-2.1: unit }
depends_on: [T1]
verify: npm test -- refund`;

function file(details: string, overview?: string) {
  const parsed = parseTasks(details);
  const index = overview ?? taskIndex(parsed.tasks, story);
  return { text: `# Tasks\n\nSummary.\n\n## Overview\n\n${index}\n\n## Details\n\n${details}`, tasks: parseTasks(details).tasks };
}

describe('tasks.md in two layers', () => {
  const details = task('T1', 'Customers pay by card', T1) + task('T2', 'Customers get refunds', T2);

  test('test_levels and evidence feed the same model as the older tests lists', () => {
    const [t1, t2] = parseTasks(details).tasks;
    expect(t1).toMatchObject({ tests: { unit: ['S-1.1/C1'], e2e: ['S-1.1'] }, evidence: 'tdd', characterization: false });
    expect(t2).toMatchObject({ tests: { unit: ['S-2.1'], e2e: [] }, evidence: 'tdd' });
    const mutation = parseTasks(task('T3', 'Pin the error path', T2.replace('depends_on: [T1]', 'evidence: mutation'))).tasks[0]!;
    expect(mutation.characterization).toBe(true);
    const none = parseTasks(task('T4', 'Document refunds', 'project: shop\nkind: docs\ntier: fast\nevidence: none')).tasks[0]!;
    expect(none.evidence).toBe('none');
  });

  test('the Overview is generated by acceptance criterion, with [P] and a checkpoint per group', () => {
    const tasks = parseTasks(details).tasks;
    expect(taskIndex(tasks, story)).toBe(
      [
        '### AC-1 — Pay by card',
        '',
        '- [ ] T1 [AC-1] [P] Customers pay by card — `src/pay.ts`',
        '',
        '**Checkpoint:** `npm test -- pay` passes (T1); this confirms AC-1 before the next group.',
        '',
        '### AC-2 — Refund',
        '',
        '- [ ] T2 [AC-2] Customers get refunds — `src/refund.ts`',
        '',
        '**Checkpoint:** `npm test -- refund` passes (T2); this confirms AC-2 before the next group.',
      ].join('\n'),
    );
    const { text, tasks: parsed } = file(details);
    expect(taskLayoutIssues(text, parsed, story)).toEqual([]);
  });

  test('a stale Overview fails, and --index --write puts the generated one back', () => {
    const { text, tasks } = file(details, '- [ ] T1 something else');
    expect(taskLayoutIssues(text, tasks, story)).toEqual([expect.stringMatching(/Overview does not match the details/)]);
    expect(taskLayoutIssues(withIndex(text, tasks, story), tasks, story)).toEqual([]);
  });

  test('the validator rejects titles with paths, prose in YAML, more than 5 Done when bullets, missing levels and HTML comments', () => {
    const bad =
      task('T1', 'Update `src/pay.ts`', `${T1}\ndod: [all green]`) +
      task(
        'T2',
        'Customers get refunds',
        T2.replace('test_levels: { S-2.1: unit }', 'test_levels: { S-9.9: unit }'),
        ['- **Done when:**', ...Array.from({ length: 6 }, (_, i) => `  - item ${i}`), '<!-- keep this -->'].join('\n'),
      );
    const { text, tasks } = file(bad);
    expect(taskLayoutIssues(text, tasks, story).sort()).toEqual(
      [
        'T1: the title names a file; say the result instead',
        'T1: prose fields in YAML (dod): use test_levels, evidence and Done when',
        'T2: Done when has 6 bullets; at most 5',
        'T2: no test level for S-2.1',
        'T2: test_levels names scenarios the task does not cite: S-9.9',
        'tasks.md: HTML comments are not allowed; write the text or drop it',
      ].sort(),
    );
  });

  test('a tasks.md in the older one-layer layout is not held to the new rules', () => {
    const older = `# Tasks\n\n${task('T1', 'Format `src/cli/skills.ts`', 'project: shop\ntier: fast\ntests: { unit: [lists skills] }\ndod: [done]')}`;
    expect(taskLayoutIssues(older, parseTasks(older).tasks, story)).toEqual([]);
    expect(parseTasks(older).tasks[0]).toMatchObject({ tests: { unit: ['lists skills'], e2e: [] }, dod: ['done'], evidence: 'tdd' });
  });
});
