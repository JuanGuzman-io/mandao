import type { Command, Option } from 'commander';

import { DEPRECATED_COMMANDS, MAINTAINER_COMMANDS, USER_COMMANDS } from '../schemas/cli-commands.js';

export { DEPRECATED_COMMANDS, MAINTAINER_COMMANDS, USER_COMMANDS };

interface Entry {
  path: string;
  usage: string;
  options: string[];
  description: string;
}

const hidden = (c: Command) => (c as unknown as { _hidden?: boolean })._hidden === true;

function optionText(o: Option): string {
  const value = o.defaultValue === undefined || o.defaultValue === false || o.negate ? '' : ` (default: ${String(o.defaultValue)})`;
  return `\`${o.flags}\`${value}`;
}

/** Every leaf command (and every command with an action) of the program, with its arguments and options. */
function entries(command: Command, prefix: string[] = []): Entry[] {
  return command.commands
    .filter((c) => !hidden(c))
    .flatMap((c) => {
      const path = [...prefix, c.name()];
      const args = c.registeredArguments.map((a) =>
        a.required ? `<${a.name()}${a.variadic ? '...' : ''}>` : `[${a.name()}${a.variadic ? '...' : ''}]`,
      );
      const self: Entry = {
        path: path.join(' '),
        usage: ['mandao', ...path, ...args].join(' '),
        options: c.options.filter((o) => !o.hidden).map(optionText),
        description: c.description(),
      };
      const children = entries(c, path);
      return c.commands.length && !(c as unknown as { _actionHandler?: unknown })._actionHandler ? children : [self, ...children];
    });
}

const row = (e: Entry, note?: string) =>
  `| \`${e.usage}\` | ${e.options.join(' · ') || '—'} | ${(note ? `**Deprecated:** ${note}. ` : '') + e.description.replace(/\|/g, '\\|')} |`;

const table = (rows: string[]) => ['| Command | Options | What it does |', '|---|---|---|', ...rows].join('\n');

/** The command index of `docs/cli.md`, derived from the program so no command or flag goes undocumented. */
export function cliReference(program: Command): string {
  const all = entries(program);
  const user = new Set<string>(USER_COMMANDS.map((c) => c.path));
  const maintainer = new Set<string>(MAINTAINER_COMMANDS);
  const pick = (test: (e: Entry) => boolean) => all.filter(test);
  const internal = pick((e) => e.path.startsWith('run ') && !user.has(e.path) && !maintainer.has(e.path));
  const unclassified = pick((e) => !e.path.startsWith('run ') && !user.has(e.path) && !DEPRECATED_COMMANDS[e.path] && e.path !== 'run');
  if (unclassified.length)
    throw new Error(`classify these commands in src/cli/cli-reference.ts: ${unclassified.map((e) => e.path).join(', ')}`);
  return [
    '<!-- mandao:cli-index:begin — generated by `npm run docs:cli` from the CLI definitions; edit src/cli/cli-reference.ts -->',
    '## Command index',
    '',
    'Every command and flag the CLI defines. A test fails when this index and the CLI differ.',
    '',
    '### Terminal commands (you type them)',
    '',
    table(pick((e) => user.has(e.path)).map((e) => row(e))),
    '',
    '### Maintainer tools',
    '',
    table(pick((e) => maintainer.has(e.path)).map((e) => row(e))),
    '',
    '### Internal scripts (the agent commands run them)',
    '',
    'Compact JSON on stdout (`MANDAO_JSON=pretty` for people). You do not need to run them by hand.',
    '',
    table(internal.map((e) => row(e))),
    '',
    '### Deprecated',
    '',
    table(pick((e) => Boolean(DEPRECATED_COMMANDS[e.path])).map((e) => row(e, DEPRECATED_COMMANDS[e.path]))),
    '<!-- mandao:cli-index:end -->',
  ].join('\n');
}
