import { posix } from 'node:path';
import type { TokenSyntax } from '../render/render.js';
import type { HarnessId } from '../schemas/index.js';
import { commandName, frontmatter, generatedNotice, renderCommandBody, renderContext, selectCommands } from './shared.js';
import type { AdapterInput, GeneratedFile } from './types.js';

/** Harnesses that read mandaos from `.agents/skills/`: one set of files serves all of them (ADR 0019). */
export const AGENTS_SKILLS_READERS = ['codex', 'antigravity'] as const satisfies readonly HarnessId[];
type Reader = (typeof AGENTS_SKILLS_READERS)[number];

/** The reader that owns the shared files: Codex when active, so its output never depends on the others. */
export function agentsSkillsOwner(harnesses: readonly string[]): Reader | undefined {
  return AGENTS_SKILLS_READERS.find((h) => harnesses.includes(h));
}

/** Codex invokes a skill as `$name`, Antigravity as `/name`; skills receive the user's message as text. */
function syntaxFor(readers: Reader[]): TokenSyntax {
  const call = (id: string) =>
    readers.length > 1
      ? `$${commandName(id)} (\`/${commandName(id)}\` in Antigravity)`
      : readers[0] === 'codex'
        ? `$${commandName(id)}`
        : `/${commandName(id)}`;
  return {
    args: () => 'the text the user wrote after the skill name',
    arg: (_meta, name) => `<${name}>`,
    command: call,
  };
}

/** Mandaos are given explicitly: Codex must not pick them up on its own. */
const OPENAI_YAML = `# Generated by mandao: mandaos are invoked explicitly, never implicitly.
policy:
  allow_implicit_invocation: false
`;

/**
 * Mandaos as skills in `.agents/skills/` (project) or `skills/` under the harness home (global), rendered
 * once for every active reader with frontmatter valid for all (`name`, `description`). Only the owner
 * renders them; conditionals see the owner as the harness.
 */
export function renderAgentsSkills(input: AdapterInput, self: Reader): GeneratedFile[] {
  const readers = AGENTS_SKILLS_READERS.filter((h) => input.config.harnesses.includes(h) || h === self);
  const owner = agentsSkillsOwner(readers) ?? self;
  if (owner !== self) return [];
  const ctx = renderContext(input, owner);
  const syntax = syntaxFor(input.scope === 'global' ? [self] : readers);
  const skillsDir = input.scope === 'global' ? 'skills' : '.agents/skills';
  return selectCommands(input).flatMap((cmd): GeneratedFile[] => {
    const from = `command:${cmd.meta.id}`;
    const dir = posix.join(skillsDir, commandName(cmd.meta.id));
    const head = frontmatter({ name: commandName(cmd.meta.id), description: cmd.meta.description, ...cmd.meta.harness[owner] });
    const content = `${head}${generatedNotice(input.version, from)}\n\n${renderCommandBody(cmd, ctx, syntax)}`;
    const skill: GeneratedFile = {
      path: posix.join(dir, 'SKILL.md'),
      content,
      ownership: 'owned',
      from,
      harness: owner,
      scope: input.scope,
    };
    if (!readers.includes('codex')) return [skill];
    return [
      skill,
      { path: posix.join(dir, 'agents/openai.yaml'), content: OPENAI_YAML, ownership: 'owned', from, harness: owner, scope: input.scope },
    ];
  });
}
