import { stringify as stringifyYaml } from 'yaml';
import type { ResolvedCommand, ResolvedPersona } from '../resolver/resolve.js';
import { applyConditionals, contextFromConfig, renderBody, type RenderContext, type TokenSyntax } from '../render/render.js';
import type { Capability, HarnessId, Tier } from '../schemas/index.js';
import type { AdapterInput } from './types.js';

export const commandName = (id: string) => `mandao-${id}`;

export const generatedNotice = (version: string, from: string) =>
  `<!-- Generated by mandao ${version} from ${from}. Do not edit: changes belong in .mandao/overrides/. -->`;

/** YAML frontmatter with keys in insertion order; undefined values are dropped. */
export function frontmatter(data: Record<string, unknown>): string {
  const clean = Object.fromEntries(Object.entries(data).filter(([, v]) => v !== undefined));
  return `---\n${stringifyYaml(clean, { lineWidth: 0 }).trimEnd()}\n---\n`;
}

export function argumentHint(cmd: ResolvedCommand): string | undefined {
  if (!cmd.meta.arguments.length) return undefined;
  return cmd.meta.arguments.map((a) => (a.required ? `<${a.name}>` : `[${a.name}]`)).join(' ');
}

/** Commands installed for this scope and for at least one profile in use. */
export function selectCommands(input: AdapterInput): ResolvedCommand[] {
  const profiles = new Set(input.config.projects.map((p) => p.profile));
  return input.resolution.commands.filter((c) => {
    const scopeOk = input.scope === 'global' ? c.meta.scope !== 'project' : c.meta.scope !== 'global';
    return scopeOk && c.meta.profiles.some((p) => profiles.has(p));
  });
}

export function mapCapabilities(caps: Capability[], table: Record<Capability, string[]>): string[] {
  return [...new Set(caps.flatMap((c) => table[c]))];
}

export function modelFor(input: AdapterInput, harness: HarnessId, tier: Tier): string | undefined {
  return input.models.harnesses[harness]?.[tier];
}

export function renderContext(input: AdapterInput, harness: HarnessId): RenderContext {
  return { ...contextFromConfig(input.config, harness, input.version), commands: new Set(input.resolution.commands.map((c) => c.meta.id)) };
}

export function renderCommandBody(cmd: ResolvedCommand, ctx: RenderContext, syntax: TokenSyntax): string {
  try {
    return renderBody(cmd.meta, cmd.body, ctx, syntax).trimEnd() + '\n';
  } catch (e) {
    throw new Error(`command "${cmd.meta.id}" (${ctx.harness}): ${(e as Error).message}`);
  }
}

/** Personas accept conditionals, paths, version and command tokens, but no arguments, templates or scripts. */
export function renderPersonaBody(persona: ResolvedPersona, ctx: RenderContext, syntax: TokenSyntax): string {
  const meta = {
    id: persona.meta.id,
    arguments: [],
    templates: [],
    scripts: [],
  } as unknown as ResolvedCommand['meta'];
  try {
    return renderBody(meta, applyConditionals(persona.body, ctx), ctx, syntax).trimEnd() + '\n';
  } catch (e) {
    throw new Error(`persona "${persona.meta.id}" (${ctx.harness}): ${(e as Error).message}`);
  }
}

/** Warns when a persona that must differ from another resolves to the same model. */
export function modelSeparationWarnings(input: AdapterInput, harness: HarnessId): string[] {
  const warnings: string[] = [];
  const byId = new Map(input.resolution.personas.map((p) => [p.meta.id, p]));
  for (const p of input.resolution.personas) {
    const otherId = p.meta.must_differ_from;
    const other = otherId ? byId.get(otherId) : undefined;
    if (!other) continue;
    const a = modelFor(input, harness, p.meta.tier);
    const b = modelFor(input, harness, other.meta.tier);
    if (!a || !b) {
      warnings.push(`${harness}: "${p.meta.id}" must use a different model than "${other.meta.id}", but .mandao/models.yml has no models for ${harness}; the rule is enforced by instruction only`);
    } else if (a === b) {
      warnings.push(`${harness}: "${p.meta.id}" and "${other.meta.id}" both resolve to model "${a}"`);
    }
  }
  return warnings;
}
