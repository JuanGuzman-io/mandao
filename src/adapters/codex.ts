import { posix } from 'node:path';
import type { TokenSyntax } from '../render/render.js';
import {
  commandName,
  frontmatter,
  generatedNotice,
  personaVariants,
  renderCommandBody,
  renderContext,
  renderPersonaBody,
  selectCommands,
} from './shared.js';
import type { Adapter, AdapterInput, GeneratedFile } from './types.js';

/** Codex invokes a skill as `$name`; skills receive the user's message, there are no placeholders. */
const syntax: TokenSyntax = {
  args: () => 'the text the user wrote after the skill name',
  arg: (_meta, name) => `<${name}>`,
  command: (id) => `$${commandName(id)}`,
};

/** A TOML string: a literal multi-line string when safe, otherwise a JSON-escaped basic string. */
export function tomlString(value: string): string {
  return value.includes("'''") ? JSON.stringify(value) : `'''\n${value}'''`;
}

/** Codex agent names in the docs are snake_case (`pr_explorer`). */
const agentName = (name: string) => name.replace(/-/g, '_');

/** Mandaos are given explicitly: Codex must not pick them up on its own. */
const OPENAI_YAML = `# Generated by mandao: mandaos are invoked explicitly, never implicitly.
policy:
  allow_implicit_invocation: false
`;

/** Mandaos as skills in `.agents/skills/` (project) or `~/.agents/skills/` (global), never implicit. */
function renderSkills(input: AdapterInput): GeneratedFile[] {
  const ctx = renderContext(input, 'codex');
  const skillsDir = input.scope === 'global' ? 'skills' : '.agents/skills';
  return selectCommands(input).flatMap((cmd): GeneratedFile[] => {
    const from = `command:${cmd.meta.id}`;
    const dir = posix.join(skillsDir, commandName(cmd.meta.id));
    const head = frontmatter({ name: commandName(cmd.meta.id), description: cmd.meta.description, ...cmd.meta.harness.codex });
    const content = `${head}${generatedNotice(input.version, from)}\n\n${renderCommandBody(cmd, ctx, syntax)}`;
    return [
      { path: posix.join(dir, 'SKILL.md'), content, ownership: 'owned', from, harness: 'codex', scope: input.scope },
      { path: posix.join(dir, 'agents/openai.yaml'), content: OPENAI_YAML, ownership: 'owned', from, harness: 'codex', scope: input.scope },
    ];
  });
}

/** Personas as custom agents with their own model and reasoning effort. */
function renderAgents(input: AdapterInput): GeneratedFile[] {
  const ctx = renderContext(input, 'codex');
  return input.resolution.personas.flatMap((persona) => {
    const body = renderPersonaBody(persona, ctx, syntax);
    return personaVariants(persona, input.models.codex).map((v): GeneratedFile => {
      const lines = [
        `# Generated by mandao ${input.version} from ${v.from}. Do not edit: changes belong in .mandao/overrides/.`,
        `name = ${JSON.stringify(agentName(v.name))}`,
        `description = ${JSON.stringify(v.description)}`,
        ...(v.model ? [`model = ${JSON.stringify(v.model)}`] : []),
        ...(v.effort ? [`model_reasoning_effort = ${JSON.stringify(v.effort)}`] : []),
        `developer_instructions = ${tomlString(`${v.preface ? `${v.preface}\n\n` : ''}${body}`)}`,
      ];
      return {
        path: `.codex/agents/${v.name}.toml`,
        content: `${lines.join('\n')}\n`,
        ownership: 'owned',
        from: v.from,
        harness: 'codex',
        scope: 'project',
      };
    });
  });
}

/**
 * Codex (OpenAI): mandaos become skills in `.agents/skills/` (custom prompts are deprecated and
 * user-only), personas become custom agents in `.codex/agents/*.toml` with their own model and effort.
 */
export const codexAdapter: Adapter = {
  id: 'codex',
  name: 'Codex',
  verified: {
    date: '2026-10-20',
    docs: [
      'https://learn.chatgpt.com/docs/build-skills.md',
      'https://learn.chatgpt.com/docs/agent-configuration/subagents.md',
      'https://learn.chatgpt.com/docs/agent-configuration/agents-md.md',
    ],
  },
  render(input) {
    return { files: [...renderSkills(input), ...(input.scope === 'project' ? renderAgents(input) : [])], warnings: [] };
  },
};
