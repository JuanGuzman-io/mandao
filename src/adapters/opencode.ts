import type { TokenSyntax } from '../render/render.js';
import type { Capability } from '../schemas/index.js';
import {
  commandName,
  frontmatter,
  generatedNotice,
  openByHand,
  personaVariants,
  renderCommandBody,
  renderContext,
  renderPersonaBody,
  selectCommands,
} from './shared.js';
import type { Adapter, AdapterInput, GeneratedFile } from './types.js';

const syntax: TokenSyntax = {
  args: () => '$ARGUMENTS',
  // OpenCode passes positional arguments as $1, $2… in the order the command declares them.
  arg: (meta, name) => `$${meta.arguments.filter((a) => !a.flag).findIndex((a) => a.name === name) + 1}`,
  command: (id) => `/${commandName(id)}`,
};

/** Tools a persona without the capability must not use (OpenCode `permission`, `deny`). */
const DENY_WITHOUT: Partial<Record<Capability, string>> = { edit: 'edit', shell: 'bash', web: 'webfetch', agents: 'task' };

function permission(caps: Capability[]): Record<string, string> | undefined {
  const deny = Object.entries(DENY_WITHOUT)
    .filter(([cap]) => !caps.includes(cap as Capability))
    .map(([, tool]) => [tool, 'deny'] as const);
  return deny.length ? Object.fromEntries(deny) : undefined;
}

/**
 * Leader: the session agent the implement and resume commands switch to. Reviewer: `all`, usable both as
 * a subagent and by `opencode run --agent` as a separate process (OpenCode 1 fell back to the default
 * agent for a `subagent`; 2 does not, `all` works in both). Everyone else is a subagent.
 */
const modeFor = (id: string) => (id === 'leader' ? 'primary' : id === 'reviewer' ? 'all' : 'subagent');

function renderAgents(input: AdapterInput): GeneratedFile[] {
  const ctx = renderContext(input, 'opencode');
  return input.resolution.personas.flatMap((persona) => {
    const body = renderPersonaBody(persona, ctx, syntax);
    return personaVariants(persona, input.models.opencode).map((v): GeneratedFile => {
      const head = frontmatter({
        description: v.description,
        mode: modeFor(persona.meta.id),
        model: v.model,
        // OpenCode model variants are effort names (low … max); only set when an effort is chosen. OpenCode 2
        // migrates `variant` and `permission` (v1 keys) to its own `model#variant` and rules (ADR 0025).
        variant: v.effort,
        permission: permission(persona.meta.capabilities),
        ...persona.meta.harness.opencode,
      });
      return {
        path: `.opencode/agents/${v.name}.md`,
        content: `${head}${generatedNotice(input.version, v.from)}\n\n${v.preface ? `${v.preface}\n\n` : ''}${body}`,
        ownership: 'owned',
        from: v.from,
        harness: 'opencode',
        scope: 'project',
      };
    });
  });
}

/**
 * OpenCode also reads `.claude/skills/` and `.agents/skills/`, where other harnesses' mandaos live. The
 * commands below already win the `/` menu by name; this config hides those copies from the skill tool
 * too, so each mandao exists once in OpenCode. OpenCode merges `.opencode/opencode.jsonc` with the
 * user's own config, which Mandao never touches.
 */
function renderConfig(input: AdapterInput): GeneratedFile {
  const content = [
    `// Generated by mandao ${input.version}. Do not edit: changes belong in .mandao/overrides/.`,
    "// Mandao's commands live in .opencode/commands; the copies other harnesses keep in .claude/skills",
    '// and .agents/skills stay hidden from the skill tool.',
    '{',
    '  "$schema": "https://opencode.ai/config.json",',
    '  "permission": { "skill": { "mandao-*": "deny" } }',
    '}',
    '',
  ].join('\n');
  return { path: '.opencode/opencode.jsonc', content, ownership: 'owned', from: 'config:skills', harness: 'opencode', scope: 'project' };
}

/**
 * OpenCode (provider-agnostic): mandaos become commands, personas become agents with their own
 * `provider/model`. Instructions come from the AGENTS.md blocks, which OpenCode reads first.
 */
export const opencodeAdapter: Adapter = {
  id: 'opencode',
  name: 'OpenCode',
  session: {
    invoke: (command) => `/${command}`,
    enterWorktree: false,
    newConversation: '/new',
    resume: (worktree, first) => openByHand('opencode', worktree, first),
  },
  testedNote:
    'live-tested in the TUI (2.1.1, acceptance 2026-10-20); invoking mandaos non-interactively needs OpenCode 2 server API (session.command): OPEN',
  verified: {
    date: '2026-10-20',
    docs: [
      'https://opencode.ai/docs/commands/',
      'https://opencode.ai/docs/agents/',
      'https://opencode.ai/docs/skills/',
      'https://github.com/anomalyco/opencode/tree/v1.19.3/packages/opencode/src',
      'https://github.com/anomalyco/opencode/tree/v2.1.1/packages',
    ],
  },
  render(input) {
    const ctx = renderContext(input, 'opencode');
    const dir = input.scope === 'global' ? 'commands' : '.opencode/commands';
    const files = selectCommands(input).map((cmd): GeneratedFile => {
      const from = `command:${cmd.meta.id}`;
      const head = frontmatter({ description: cmd.meta.description, ...cmd.meta.harness.opencode });
      return {
        path: `${dir}/${commandName(cmd.meta.id)}.md`,
        content: `${head}${generatedNotice(input.version, from)}\n\n${renderCommandBody(cmd, ctx, syntax)}`,
        ownership: 'owned',
        from,
        harness: 'opencode',
        scope: input.scope,
      };
    });
    if (input.scope === 'project') files.push(...renderAgents(input), renderConfig(input));
    return { files, warnings: [] };
  },
};
