import { posix } from 'node:path';
import type { ResolvedCommand } from '../resolver/resolve.js';
import { USER_COMMANDS } from '../schemas/cli-commands.js';
import { argumentSyntax, argumentUsage } from '../schemas/index.js';
import { wrapBlock } from '../writer/blocks.js';
import { commandName, selectCommands } from './shared.js';
import type { AdapterInput, AdapterOutput, GeneratedFile } from './types.js';

const block = (version: string, lines: string[]) =>
  wrapBlock('AGENTS.md', [
    `<!-- Managed by mandao ${version}. Edit outside these markers; this block is regenerated by \`mandao sync\`. -->`,
    '',
    ...lines,
    '',
  ]);

const workspaceRelative = (from: string, to: string) => posix.relative(from, to) || '.';

/** The subject and emoji lines of the guide's Commits section; plain Conventional Commits when `commits.emoji` is false. */
function commitSubjectLines(config: AdapterInput['config']): string[] {
  const emoji = config.commits.emoji;
  if (emoji === false)
    return [
      `Subject: \`<type>(<scope>): <subject>\` (plain Conventional Commits, no emoji), imperative mood, at most ${config.commits.max_subject_length} characters.`,
      '',
      'A breaking change adds `!` after the scope and a `BREAKING CHANGE:` trailer.',
    ];
  return [
    `Subject: \`<emoji> <type>(<scope>): <subject>\`, imperative mood, at most ${config.commits.max_subject_length} characters without the emoji.`,
    '',
    `Emoji per type: ${Object.entries(emoji)
      .filter(([k]) => k !== 'breaking')
      .map(([k, v]) => `${k} ${v}`)
      .join(', ')}. A breaking change uses ${emoji.breaking} instead of the type emoji.`,
  ];
}

/** The full guide: workspace, commands, rules and commit conventions. Read when a mandao runs, not loaded by every session. */
function guide(input: AdapterInput): string {
  const { config } = input;
  const commands = selectCommands({ ...input, scope: 'project' });
  const stable = commands.filter((c) => c.meta.status === 'stable');
  const stubs = commands.filter((c) => c.meta.status === 'stub');
  const t = config.commits.trailers;

  const lines = [
    `<!-- Generated by mandao ${input.version}. Do not edit: run \`mandao sync\`. -->`,
    '',
    '# Mandao guide',
    '',
    'This workspace uses [Mandao](https://www.npmjs.com/package/mandao) for spec-driven development.',
    'Every command is a *mandao*: invoke it as `/mandao-<command>` in your agent.',
    '',
    `Flow: ${['constitution', 'story', 'specify', '[clarify]', 'tasks', 'implement', 'verify', 'close']
      .map((s) => `\`${s}\``)
      .join(' → ')}`,
    '',
    '## Workspace',
    '',
    `- Mode: \`${config.workspace}\``,
    `- Specs: \`${config.paths.specs}/<id>-<slug>/\` (id from the tracker, or a sequential \`NNN\` when there is none)`,
    `- Workspace constitution: \`${config.paths.constitution}/\`; each project may extend it in \`<project>/${config.paths.constitution}/\``,
    '',
    '| Project | Path | Profile |',
    '|---|---|---|',
    ...config.projects.map((p) => `| ${p.name} | \`${p.path}\` | ${p.profile} |`),
    '',
    '## Commands',
    '',
    ...stable.flatMap(commandEntry),
    ...(stubs.length ? ['', `Not implemented yet: ${stubs.map((c) => `\`/${commandName(c.meta.id)}\``).join(', ')}.`] : []),
    '',
    '## Terminal commands',
    '',
    'The commands above run every other script themselves. These are the ones you type (`mandao <command> --help` lists the flags; `docs/cli.md` in the Mandao repository has the full index):',
    '',
    ...USER_COMMANDS.map((c) => `- \`mandao ${c.path}\` — ${c.summary}`),
    '',
    '## Rules',
    '',
    '- Never invent context. Mark gaps as `ASSUMPTION`, `OPEN` or `CONFLICT`, always with the source.',
    '- If a code graph exists (e.g. graphify), query it before searching files.',
    `- Write business content (story, release notes, questions to the ${config.roles.po}, product context) in \`${config.language.business}\` and technical content (requirements, design, tasks, technical docs) in \`${config.language.technical}\`. Section headings, keywords (GIVEN/WHEN/THEN, MUST, AC-n, FR-n) and markers stay in English. Code and commits are always in English.`,
    '- Spec status: `draft → approved → in-progress → blocked → verified → closed | abandoned`.',
    '- A human approves every significant change and anything published outside the repository.',
    `- Templates live in \`${posix.join(workspaceRelative(config.home, '.'), '.mandao/templates/<profile>/')}\`; use the profile of the project you are working on.`,
    '',
    '## Commits',
    '',
    ...commitSubjectLines(config),
    '',
    `Trailers: \`${t.refs}: <tracker id>\`, \`${t.task}: <task>\`, \`${t.acs}: <AC ids>\`, \`${t.quick}: <name>\` for quick changes.`,
  ];
  return `${lines.join('\n')}\n`;
}

/** The guide's path relative to the workspace home, where AGENTS.md lives. */
const GUIDE = '.mandao/guide.md';

/**
 * The block every session loads (AGENTS.md is read even when Mandao is not used): only a pointer to the
 * guide, so the cost of having Mandao installed is a couple of lines (cost-conscious design).
 */
function rootBlock(input: AdapterInput): string {
  return block(input.version, [
    '## Mandao',
    '',
    `Spec-driven development with [Mandao](https://www.npmjs.com/package/mandao): commands are \`/mandao-<command>\`. Before running one, or editing \`${input.config.paths.specs}/\` or \`${input.config.paths.constitution}/\`, read [${GUIDE}](${GUIDE}).`,
  ]);
}

function projectBlock(input: AdapterInput, project: AdapterInput['config']['projects'][number]): string {
  const home = input.config.home;
  const toRoot = workspaceRelative(project.path, home);
  return block(input.version, [
    '## Mandao',
    '',
    `Project \`${project.name}\` (profile \`${project.profile}\`) in a Mandao ${input.config.workspace} workspace.`,
    '',
    `- Workspace guide: \`${posix.join(toRoot, GUIDE)}\``,
    `- Project constitution: \`${input.config.paths.constitution}/\` (extends \`${posix.join(toRoot, input.config.paths.constitution)}/\`)`,
    `- Canonical specs: \`${posix.join(toRoot, input.config.paths.specs)}/\``,
    ...(input.config.workspace === 'polyrepo'
      ? [
          `- This repository receives spec slices in \`${input.config.paths.specs}/<id>/spec-ref.md\`; the canonical spec stays in the workspace.`,
        ]
      : []),
  ]);
}

/** Universal fallback: a managed block in the root AGENTS.md and in each project's AGENTS.md. */
/**
 * One command in the guide: its usage line, what it does, then each argument as typed with its default and an
 * example (phase 19: the project gets every argument, not only the repository's pages).
 */
function commandEntry(c: ResolvedCommand): string[] {
  const m = c.meta;
  const usage = [`/${commandName(m.id)}`, ...m.arguments.map(argumentUsage)].join(' ');
  return [
    `- \`${usage}\` — ${m.description}`,
    ...m.arguments.map((a) => `  - \`${argumentSyntax(a)}\`${a.default ? ` (default \`${a.default}\`)` : ''}: ${a.description}`),
    ...m.examples.slice(0, 2).map((e) => `  - e.g. \`${e.run}\` — ${e.does}`),
  ];
}

export function renderAgentsMd(input: AdapterInput): AdapterOutput {
  const files: GeneratedFile[] = [
    {
      path: posix.join(input.config.home, 'AGENTS.md'),
      content: rootBlock(input),
      ownership: 'managed-block',
      from: 'block:mandao',
      harness: 'agents-md',
      scope: 'project',
    },
    {
      path: posix.join(input.config.home, GUIDE),
      content: guide(input),
      ownership: 'owned',
      from: 'guide:mandao',
      harness: 'agents-md',
      scope: 'project',
    },
  ];
  for (const project of input.config.projects) {
    if (project.path === '.' || project.path === input.config.home) continue;
    files.push({
      path: posix.join(project.path, 'AGENTS.md'),
      content: projectBlock(input, project),
      ownership: 'managed-block',
      from: `block:mandao:${project.name}`,
      harness: 'agents-md',
      scope: 'project',
    });
  }
  return { files, warnings: [] };
}
