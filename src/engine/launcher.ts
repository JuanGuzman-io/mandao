import type { Config } from '../schemas/index.js';

export const LAUNCHER_PATH = '.mandao/bin/mandao.mjs';

/** How generated commands call Mandao: through the launcher, so the runner is resolved at run time. */
export const launcherCommand = () => `node ${LAUNCHER_PATH}`;

/**
 * A dependency-free Node script that finds Mandao in this order: local `node_modules/.bin`,
 * a global install on PATH, then `npx -y mandao@<locked version>`. `scripts.runner` forces one.
 * With MANDAO_LAUNCHER_PRINT=1 it prints its choice as JSON instead of running it (used by doctor).
 */
export function launcherScript(version: string, runner: Config['scripts']['runner']): string {
  return `#!/usr/bin/env node
// Generated by mandao ${version} from .mandao/config.yml (scripts.runner). Do not edit: run \`mandao sync\`.
import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { delimiter, dirname, join } from 'node:path';

const VERSION = ${JSON.stringify(version)};
const RUNNER = ${JSON.stringify(runner)};
const BIN = process.platform === 'win32' ? ['mandao.cmd', 'mandao.exe', 'mandao'] : ['mandao'];

function findLocal() {
  for (let dir = process.cwd(); ; dir = dirname(dir)) {
    for (const name of BIN) {
      const candidate = join(dir, 'node_modules', '.bin', name);
      if (existsSync(candidate)) return candidate;
    }
    if (dirname(dir) === dir) return undefined;
  }
}

function findGlobal() {
  for (const dir of (process.env.PATH ?? '').split(delimiter)) {
    if (!dir || dir.includes(join('node_modules', '.bin'))) continue;
    for (const name of BIN) {
      const candidate = join(dir, name);
      if (existsSync(candidate)) return candidate;
    }
  }
  return undefined;
}

const args = process.argv.slice(2);
const local = RUNNER === 'auto' || RUNNER === 'local' ? findLocal() : undefined;
const global = !local && (RUNNER === 'auto' || RUNNER === 'global') ? findGlobal() : undefined;
const choice = local
  ? { source: 'local', command: local, args }
  : global
    ? { source: 'global', command: global, args }
    : RUNNER === 'auto' || RUNNER === 'npx'
      ? { source: 'npx', command: 'npx', args: ['-y', \`mandao@\${VERSION}\`, ...args] }
      : undefined;

if (process.env.MANDAO_LAUNCHER_PRINT === '1') {
  console.log(JSON.stringify(choice ?? { source: 'none', runner: RUNNER }));
  process.exit(0);
}
if (!choice) {
  console.error(\`mandao: no \${RUNNER} installation found (scripts.runner: \${RUNNER} in .mandao/config.yml)\`);
  process.exit(127);
}
const result = spawnSync(choice.command, choice.args, { stdio: 'inherit', shell: process.platform === 'win32' });
process.exit(result.status ?? 1);
`;
}
