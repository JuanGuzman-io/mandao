import type { Config } from '../schemas/index.js';

export const COMMITLINT_PATH = '.mandao/commitlint.config.mjs';

/**
 * A commitlint config that projects extend from their own config:
 * `export default { extends: ['./.mandao/commitlint.config.mjs'] }`.
 * The header pattern accepts the emoji prefix and a plugin rule checks it matches the type.
 */
/** Turns `{type}/{id}-{slug}` into a regex source whose first group is the spec id. */
export function branchIdPattern(template: string, localPrefix: string): string {
  const escaped = template.replace(/[.*+?^$()|[\]\\]/g, '\\$&');
  return `^${escaped
    .replace('\\{type\\}', '[a-z]+')
    .replace('{type}', '[a-z]+')
    .replace('{id}', `((?:[A-Z][A-Z0-9_]*|${localPrefix})-\\d+)`)
    .replace('{slug}', '.+')}$`;
}

export function commitlintConfig(config: Config, version: string): string {
  const { emoji, max_subject_length: maxSubjectLength, trailers } = config.commits;
  const branchRe = branchIdPattern(config.spec.branch, config.spec.local_prefix);
  return `// Generated by mandao ${version} from .mandao/config.yml (commits). Do not edit: run \`mandao sync\`.
import { execSync } from 'node:child_process';

const BRANCH_RE = new RegExp(${JSON.stringify(branchRe)});
const REFS = ${JSON.stringify(trailers.refs)};

/** The spec id of the current branch (or MANDAO_SPEC_ID), when a spec is active. */
const activeId = (() => {
  if (process.env.MANDAO_SPEC_ID !== undefined) return process.env.MANDAO_SPEC_ID || undefined;
  try {
    return execSync('git rev-parse --abbrev-ref HEAD', { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim().match(BRANCH_RE)?.[1];
  } catch {
    return undefined;
  }
})();

const EMOJI = ${JSON.stringify(emoji, null, 2)};
const TYPES = Object.keys(EMOJI).filter((t) => t !== 'breaking');
const MAX = ${maxSubjectLength};

const isBreaking = (parsed) =>
  parsed.breaking === '!' || (parsed.notes ?? []).some((n) => /^BREAKING[ -]CHANGE$/.test(n.title));

export default {
  parserPreset: {
    parserOpts: {
      headerPattern: /^(\\S+) (\\w+)(?:\\(([\\w./-]+)\\))?(!)?: (.+)$/u,
      headerCorrespondence: ['emoji', 'type', 'scope', 'breaking', 'subject'],
    },
  },
  plugins: [
    {
      rules: {
        'mandao-emoji': (parsed) => {
          if (!parsed.type) return [false, 'header must be "<emoji> <type>(<scope>): <subject>"'];
          const expected = isBreaking(parsed) ? EMOJI.breaking : EMOJI[parsed.type];
          return [parsed.emoji === expected, \`"\${parsed.type}" commits start with \${expected}\${isBreaking(parsed) ? ' (breaking change)' : ''}\`];
        },
        'mandao-refs': (parsed) => {
          if (!activeId) return [true];
          const ok = (parsed.raw ?? '')
            .split('\\n')
            .filter((line) => line.startsWith(\`\${REFS}:\`))
            .some((line) => line.slice(REFS.length + 1).split(/[\\s,]+/).includes(activeId));
          return [ok, \`spec \${activeId} is active: add the trailer "\${REFS}: \${activeId}"\`];
        },
        'mandao-header-length': (parsed) => {
          const header = parsed.header ?? '';
          const withoutEmoji = parsed.emoji ? header.slice(parsed.emoji.length + 1) : header;
          const length = [...withoutEmoji].length;
          return [length <= MAX, \`header is \${length} characters without the emoji; the limit is \${MAX}\`];
        },
      },
    },
  ],
  rules: {
    'type-enum': [2, 'always', TYPES],
    'type-empty': [2, 'never'],
    'subject-empty': [2, 'never'],
    'subject-full-stop': [2, 'never', '.'],
    'mandao-emoji': [2, 'always'],
    'mandao-header-length': [2, 'always'],
    'mandao-refs': [2, 'always'],
  },
};
`;
}
