// `npm run diagrams`: derive each specification, validate and render it with Archify, export light and
// dark SVG. Writes docs/diagrams/src/<name>.json (specification + derivedFrom) and <name>-{light,dark}.svg.
// Also writes the generated pages (docs/process-map.md, docs/commands/). A diagram whose specification
// did not change is not rendered again, so editing a command's wording needs no Archify; `--force` renders all.
// `--only a,b` limits the run; `--archify <dir>` points at the Archify skill (otherwise searched across harness folders).
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { ALL_DIAGRAMS, sources } from './derive.mjs';
import { generatedDocs } from './docs.mjs';
import { exportSvgs } from './export-svg.mjs';
import { specHash } from './hash.mjs';
import { verifiedOutput } from './verified-output.mjs';

const root = resolve(import.meta.dirname, '../..');
const arg = (name) => {
  const i = process.argv.indexOf(name);
  return i > 0 ? process.argv[i + 1] : undefined;
};
const archifyDirs = arg('--archify')
  ? [arg('--archify')]
  : [
      join(root, '.claude/skills/archify'),
      join(root, '.agents/skills/archify'),
      join(root, '.github/skills/archify'),
      join(root, '.copilot/skills/archify'),
      join(root, '.config/opencode/skills/archify'),
      join(root, '.gemini/antigravity/skills/archify'),
      join(homedir(), '.claude/skills/archify'),
      join(homedir(), '.agents/skills/archify'),
      join(homedir(), '.github/skills/archify'),
      join(homedir(), '.copilot/skills/archify'),
      join(homedir(), '.config/opencode/skills/archify'),
      join(homedir(), '.gemini/antigravity/skills/archify'),
    ];
const archify = archifyDirs.map((dir) => join(dir, 'bin/archify.mjs')).find(existsSync);
if (!archify)
  throw new Error(
    'Archify 3.2.0 is required to rebuild diagrams. Run `mandao init` and confirm the pinned install, ' +
      'or pass --archify <skill directory>.',
  );
const only = arg('--only')?.split(',');
const out = join(root, 'docs/diagrams');
mkdirSync(join(out, 'src'), { recursive: true });
const fileHash = (file) => createHash('sha256').update(readFileSync(file)).digest('hex');
const svgHashes = (name) => Object.fromEntries(['light', 'dark'].map((theme) => [theme, fileHash(join(out, `${name}-${theme}.svg`))]));


for (const [name, derive] of Object.entries(ALL_DIAGRAMS)) {
  if (only && !only.includes(name)) continue;
  const src = sources(root);
  const spec = derive(src.read);
  const hash = specHash(spec);
  const srcFile = join(out, 'src', `${name}.json`);
  const existing = existsSync(srcFile) ? JSON.parse(readFileSync(srcFile, 'utf8')) : {};
  const same = existing.specSha256 === hash;
  const svgPathsExist = ['light', 'dark'].every((theme) => existsSync(join(out, `${name}-${theme}.svg`)));
  const existingHashesMatch = svgPathsExist && ['light', 'dark'].every((theme) => {
    const file = join(out, `${name}-${theme}.svg`);
    const marker = readFileSync(file, 'utf8').includes(`spec-sha256 ${hash}`);
    return verifiedOutput(marker, existing.svgSha256?.[theme], fileHash(file));
  });
  const record = (renderedHashes) => writeFileSync(srcFile, `${JSON.stringify({ name, derivedFrom: src.derivedFrom(), specSha256: hash, svgSha256: renderedHashes, spec }, null, 2)}\n`);
  if (same && !process.argv.includes('--force') && existingHashesMatch) {
    record(svgHashes(name)); // same diagram: update source and verified SVG receipts without rendering
    continue;
  }
  const tmp = mkdtempSync(join(tmpdir(), 'mandao-diagram-'));
  try {
    const input = join(tmp, `${name}.json`);
    writeFileSync(input, `${JSON.stringify(spec, null, 2)}\n`);
    const html = join(tmp, `${name}.html`);
    const type = spec.diagram_type;
    try {
      // Archify 3.x wants portable relative paths: run it from the temporary folder.
      execFileSync('node', [archify, 'deliver', type, `${name}.json`, `${name}.html`, '--quality', spec.meta.quality_profile, '--json'], {
        cwd: tmp,
        encoding: 'utf8',
      });
    } catch (e) {
      console.error(`${name}: Archify refused the specification\n${e.stdout ?? ''}`);
      process.exitCode = 1;
      continue;
    }
    for (const [theme, svg] of Object.entries(exportSvgs(html))) {
      // The marker goes after the XML declaration, which must stay the first thing in the file.
      const marker = `<!-- mandao:diagram ${name} spec-sha256 ${hash} — generated by npm run diagrams, do not edit -->`;
      const decl = /^<\?xml[^>]*\?>\s*/.exec(svg)?.[0] ?? '';
      writeFileSync(join(out, `${name}-${theme}.svg`), `${decl.trimEnd()}${decl ? '\n' : ''}${marker}\n${svg.slice(decl.length)}\n`);
    }
    record(svgHashes(name));
    console.log(`${name}: ${type}, ${spec.nodes?.length ?? spec.states?.length} nodes, SVG light + dark`);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

if (!only) {
  const read = (rel) => readFileSync(join(root, rel), 'utf8');
  for (const [path, content] of Object.entries(generatedDocs(read))) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), content);
  }
  console.log('pages: docs/process-map.md and docs/commands/');
}
