// `npm run diagrams`: derive each specification, validate and render it with Archify, export light and
// dark SVG. Writes docs/diagrams/src/<name>.json (specification + derivedFrom) and <name>-{light,dark}.svg.
// Also writes the generated pages (docs/process-map.md, docs/commands/). A diagram whose specification
// did not change is not rendered again, so editing a command's wording needs no Archify; `--force` renders all.
// `--only a,b` limits the run; `--archify <dir>` points at the Archify skill (default ~/.claude/skills/archify).
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { ALL_DIAGRAMS, sources } from './derive.mjs';
import { generatedDocs } from './docs.mjs';
import { exportSvgs } from './export-svg.mjs';
import { specHash } from './hash.mjs';

const root = resolve(import.meta.dirname, '../..');
const arg = (name) => {
  const i = process.argv.indexOf(name);
  return i > 0 ? process.argv[i + 1] : undefined;
};
const archify = join(arg('--archify') ?? join(homedir(), '.claude/skills/archify'), 'bin/archify.mjs');
const only = arg('--only')?.split(',');
const out = join(root, 'docs/diagrams');
mkdirSync(join(out, 'src'), { recursive: true });


for (const [name, derive] of Object.entries(ALL_DIAGRAMS)) {
  if (only && !only.includes(name)) continue;
  const src = sources(root);
  const spec = derive(src.read);
  const hash = specHash(spec);
  const srcFile = join(out, 'src', `${name}.json`);
  const record = () => writeFileSync(srcFile, `${JSON.stringify({ name, derivedFrom: src.derivedFrom(), specSha256: hash, spec }, null, 2)}\n`);
  const same = existsSync(srcFile) && JSON.parse(readFileSync(srcFile, 'utf8')).specSha256 === hash;
  if (same && !process.argv.includes('--force') && ['light', 'dark'].every((t) => existsSync(join(out, `${name}-${t}.svg`)))) {
    record(); // same diagram: only its derivedFrom hashes move
    continue;
  }
  const tmp = mkdtempSync(join(tmpdir(), 'mandao-diagram-'));
  try {
    const input = join(tmp, `${name}.json`);
    writeFileSync(input, `${JSON.stringify(spec, null, 2)}\n`);
    const html = join(tmp, `${name}.html`);
    const type = spec.diagram_type;
    try {
      // Archify 3.x wants portable relative paths: run it from the temporary folder.
      execFileSync('node', [archify, 'deliver', type, `${name}.json`, `${name}.html`, '--quality', spec.meta.quality_profile, '--json'], {
        cwd: tmp,
        encoding: 'utf8',
      });
    } catch (e) {
      console.error(`${name}: Archify refused the specification\n${e.stdout ?? ''}`);
      process.exitCode = 1;
      continue;
    }
    record();
    for (const [theme, svg] of Object.entries(exportSvgs(html))) {
      // The marker goes after the XML declaration, which must stay the first thing in the file.
      const marker = `<!-- mandao:diagram ${name} spec-sha256 ${hash} — generated by npm run diagrams, do not edit -->`;
      const decl = /^<\?xml[^>]*\?>\s*/.exec(svg)?.[0] ?? '';
      writeFileSync(join(out, `${name}-${theme}.svg`), `${decl.trimEnd()}${decl ? '\n' : ''}${marker}\n${svg.slice(decl.length)}\n`);
    }
    console.log(`${name}: ${type}, ${spec.nodes?.length ?? spec.states?.length} nodes, SVG light + dark`);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

if (!only) {
  const read = (rel) => readFileSync(join(root, rel), 'utf8');
  for (const [path, content] of Object.entries(generatedDocs(read))) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), content);
  }
  console.log('pages: docs/process-map.md and docs/commands/');
}
