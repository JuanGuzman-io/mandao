// The generated Markdown around the diagrams: docs/process-map.md (after its frontmatter) and one page
// per command in docs/commands/. Pure: derived from the same sources as the diagrams, so
// `npm run diagrams:check` can regenerate it and compare without Archify.
import { commandSteps, commands, PROCESSES, STABLE_COMMANDS } from './derive.mjs';
import { parse as parseYaml } from 'yaml';

const GENERATED = '<!-- mandao:generated by npm run diagrams from the frontmatter above and core/commands; do not edit below -->';
const MARK = { required: '✅', auto: '⚙️', optional: '➕' };
// Planned commands have no command file yet (research) or only a stub (perf, audit): a short page, no diagram.
const PLANNED = { research: 'Sourced research for technical decisions.' };

export function picture(name, alt, prefix) {
  return [
    '<picture>',
    `  <source media="(prefers-color-scheme: dark)" srcset="${prefix}${name}-dark.svg">`,
    `  <img alt="${alt}" src="${prefix}${name}-light.svg">`,
    '</picture>',
  ].join('\n');
}

const frontmatterOf = (text) => /^---\n[\s\S]*?\n---\n/.exec(text)?.[0] ?? '';

/** docs/process-map.md: its frontmatter (the source) followed by the generated table and diagrams. */
export function processMap(read) {
  const text = read('docs/process-map.md');
  const fm = frontmatterOf(text);
  const { processes } = parseYaml(fm.slice(4, -5));
  const path = (p) => p.steps.map((s) => `\`${s.command}\` ${MARK[s.mark]}`).join(' → ');
  const lines = [
    fm.trimEnd(),
    '',
    '# Process map',
    '',
    GENERATED,
    '',
    '✅ required · ⚙️ triggers on its own · ➕ optional. A human approval is marked *you approve* in each diagram.',
    '',
    '| You want to… | Path |',
    '|---|---|',
    ...PROCESSES.map((id) => {
      const p = processes.find((x) => x.id === id);
      return `| [${p.title}](#${id}) | ${path(p)} |`;
    }),
    '',
  ];
  for (const id of PROCESSES) {
    const p = processes.find((x) => x.id === id);
    lines.push(`<a id="${id}"></a>`, `## ${p.title}`, '', picture(`process-${id}`, p.title, 'diagrams/'), '');
  }
  return `${lines.join('\n')}\n`;
}

const list = (items) => (items.length ? items.map((i) => `- ${i}`).join('\n') : '- —');
/** Readers see the default paths, not the template tokens (`paths` in .mandao/config.yml can change them). */
const paths = (t) =>
  t
    .replace(/\{\{paths\.specs\}\}/g, 'specs')
    .replace(/\{\{paths\.constitution\}\}/g, 'docs/constitution')
    .replace(/\{\{paths\.releases\}\}/g, 'docs/releases');

/** docs/commands/<id>.md for a stable command: what it does, reads and writes, its steps and diagram. */
export function commandPage(read, id) {
  const c = commands(read)[id];
  const m = c.meta;
  const args = (m.arguments ?? []).map((a) => `\`${a.name}\`${a.required ? ' (required)' : ''}: ${a.description}`);
  const reads = (m.inputs ?? []).map((i) => `\`${paths(i.path)}\``);
  const writes = (m.outputs ?? []).map((o) => `\`${paths(o.path)}\`${o.description ? `: ${o.description}` : ''}`);
  const scripts = (m.scripts ?? []).map((s) => `\`mandao run ${s}\``);
  const steps = commandSteps(c.body).map((s) => `${s.n}. ${s.title}${s.approval ? ' (you approve)' : ''}`);
  const approval = m.approval === 'required' ? 'Yes: it stops for your approval.' : m.approval === 'none' ? 'No.' : 'No approval step of its own.';
  return `${[
    `# /mandao-${id}`,
    '',
    GENERATED.replace('the frontmatter above and core/commands', `core/commands/${id}.md`),
    '',
    m.description,
    '',
    picture(`command-${id}`, `/mandao-${id}: steps, approval and what it writes`, '../diagrams/'),
    '',
    '## Arguments',
    '',
    list(args),
    '',
    '## Reads',
    '',
    list(reads),
    '',
    '## Writes',
    '',
    list(writes),
    '',
    '## Steps',
    '',
    steps.join('\n'),
    '',
    '## Approval',
    '',
    approval,
    '',
    '## Scripts (no tokens)',
    '',
    list(scripts),
    '',
    'Paths are the defaults; `paths` in `.mandao/config.yml` can change them.',
    '',
    `Source: [core/commands/${id}.md](../../core/commands/${id}.md).`,
  ].join('\n')}\n`;
}

/** A planned command: a short description, no diagram. */
export function plannedPage(read, id) {
  const description = PLANNED[id] ?? commands(read)[id].meta.description;
  return `# /mandao-${id}\n\n${GENERATED.replace('the frontmatter above and core/commands', 'the command list')}\n\n**Planned.** ${description}\n`;
}

/** docs/commands/README.md: the index GitHub shows under the folder's file list. */
export function commandIndex(read) {
  const all = commands(read);
  const row = (id, status) => {
    const m = all[id]?.meta;
    const what = PLANNED[id] ?? m.description;
    const approval = status === 'planned' ? '—' : m.approval === 'required' ? 'yes' : 'no';
    return `| [\`/mandao-${id}\`](${id}.md) | ${what.replace(/\|/g, '\\|')} | ${approval} | ${status === 'planned' ? '⚪ planned' : '🟢 stable'} |`;
  };
  return `${[
    '# Commands',
    '',
    GENERATED.replace('the frontmatter above and core/commands', 'core/commands'),
    '',
    'One page per command: what it does, what it reads and writes, its steps and its diagram.',
    'How they fit together: the [overview in the README](../../README.md#how-it-works) and the [process map](../process-map.md).',
    '',
    '| Command | What it does | You approve | Status |',
    '|---|---|---|---|',
    ...STABLE_COMMANDS.map((id) => row(id, 'stable')),
    ...['research', 'perf', 'audit'].map((id) => row(id, 'planned')),
  ].join('\n')}\n`;
}

/** Every generated page, path → content. */
export function generatedDocs(read) {
  return {
    'docs/process-map.md': processMap(read),
    'docs/commands/README.md': commandIndex(read),
    ...Object.fromEntries(STABLE_COMMANDS.map((id) => [`docs/commands/${id}.md`, commandPage(read, id)])),
    ...Object.fromEntries(['research', 'perf', 'audit'].map((id) => [`docs/commands/${id}.md`, plannedPage(read, id)])),
  };
}
